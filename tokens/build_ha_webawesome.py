"""Build tokens/ha-webawesome.css: Home Assistant's own Web Awesome theme layer.

Sources (home-assistant/frontend, dev branch, Apache-2.0):
  src/resources/theme/*.globals.ts and src/resources/theme/color/*.globals.ts
HA maps every --wa-* token onto its --ha-* tokens (wa.globals.ts, color/wa.globals.ts).
Everything is scoped to html.theme-ha so the page can switch it off and show plain Web Awesome.

Usage: python3 -I tokens/build_ha_webawesome.py <dir with the downloaded .ts files>
"""

import re
import sys
from pathlib import Path

SRC = Path(sys.argv[1])
OUT = Path(__file__).with_name("ha-webawesome.css")

# file, and whether its blocks are the dark variant
FILES = [
    "core.globals.ts",
    "typography.globals.ts",
    "color_core.globals.ts",
    "color_semantic.globals.ts",
    "color_color.globals.ts",
    "wa.globals.ts",
    "color_wa.globals.ts",
]


def scoped(body: str, dark: bool) -> str:
    body = re.sub(r"\$\{[^}]*\}", "", body)  # drop lit interpolations (e.g. scroll-lock styles)
    # HA's --ha-box-shadow-* tokens live outside these files; keep Web Awesome's own shadows
    body = re.sub(r"\n\s*--wa-shadow-[sml]: var\(--ha-box-shadow-[sml]\);", "", body)
    sel = "html.theme-ha[data-scheme=dark]" if dark else "html.theme-ha"
    return re.sub(r"(^|\n)(\s*)html\s*\{", lambda m: f"{m.group(1)}{m.group(2)}{sel} {{", body)


parts = [
    "/* Home Assistant theme layer for Web Awesome, generated by build_ha_webawesome.py.\n"
    " * From github.com/home-assistant/frontend (dev) src/resources/theme, Apache-2.0.\n"
    " * Scoped to html.theme-ha; dark blocks to html.theme-ha[data-scheme=dark]. */\n"
]
for name in FILES:
    src = (SRC / name).read_text()
    for const, body in re.findall(r"export const (\w+) = css`(.*?)`;", src, re.S):
        parts.append(f"/* {name}: {const} */{scoped(body, 'dark' in const.lower())}\n")

OUT.write_text("".join(parts))
print(f"wrote {OUT} ({OUT.stat().st_size} bytes)")
